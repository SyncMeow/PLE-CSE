// Writes Platform/accel/rtl/ple/ple_robot_pkg.sv from the golden robot tables (fx_pose.c, fx_fk_gen.c):
// outer (link bounding) spheres in check order, their fine spheres, and r_q of every sphere.
#include <stdio.h>
#include "fx_pose.h"

int main(void)
{
    fx_pose_init(FX_DELTA_FK_MM * 1e-3, 0, 0);                    // same eps as rrtc_fx
    printf("// GENERATED by Platform/sw_rrtc/host/fx_gen_robot_pkg.c from the golden model. Do not edit.\n");
    printf("// Panda sphere hierarchy and query radii (r_q = ceil((r + r_point) / LSB + eps), delta_FK = %g mm).\n",
           FX_DELTA_FK_MM);
    printf("/* verilator lint_off UNUSEDPARAM */\npackage ple_robot_pkg;\n\n");
    printf("  localparam int N_SPH = %d, N_OUTER = %d, N_FINE = %d;\n", FX_N_SPHERES, FX_N_OUTER, fx_outer_kid_off[FX_N_OUTER]);
    printf("  // outer spheres in the golden check order\n  localparam logic [7:0] OUTER [N_OUTER] = '{");
    for (int o = 0; o < FX_N_OUTER; ++o) printf("%s8'd%d", o ? ", " : "", fx_outer[o]);
    printf("};\n  // fine spheres of outer o: KIDS[KID_OFF[o] .. KID_OFF[o+1]-1]\n  localparam logic [7:0] KID_OFF [N_OUTER + 1] = '{");
    for (int o = 0; o <= FX_N_OUTER; ++o) printf("%s8'd%d", o ? ", " : "", fx_outer_kid_off[o]);
    printf("};\n  localparam logic [7:0] KIDS [N_FINE] = '{");
    for (int k = 0; k < fx_outer_kid_off[FX_N_OUTER]; ++k) printf("%s%s8'd%d", k ? ", " : "", k && k % 16 == 0 ? "\n      " : "", fx_outer_kids[k]);
    printf("};\n  // query radius of every sphere (LSB 2^-14 m)\n  localparam logic [13:0] RQ [N_SPH] = '{");
    for (int s = 0; s < FX_N_SPHERES; ++s) printf("%s%s14'd%u", s ? ", " : "", s && s % 12 == 0 ? "\n      " : "", fx_rq[s]);
    printf("};\n\nendpackage\n/* verilator lint_on UNUSEDPARAM */\n");
    return 0;
}
