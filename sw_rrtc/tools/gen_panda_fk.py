#!/usr/bin/env python3
"""Translate VAMP's generated Panda FK/CC (robots/panda.hh) into scalar C.

The VAMP code is straight-line FloatVector<rake> arithmetic; every statement maps 1:1 onto a
float statement, so the scalar result is bit-identical as long as the evaluation order is kept
and every double literal becomes a float literal (VAMP converts scalars to float before
broadcasting). Usage: gen_panda_fk.py <vamp>/src/impl/vamp/robots/panda.hh <out.c>
"""
import re
import sys

NUM = re.compile(r'(?<![\w\[.])(\d+\.\d*(?:[eE][-+]?\d+)?|\d+[eE][-+]?\d+)')


def extract(src, name):
    """Body lines of `inline static ... name(` up to its closing brace (8-space indent)."""
    lines = src.splitlines()
    start = next(i for i, l in enumerate(lines) if re.search(r'inline static \w+ ' + name + r'\(', l)
                 or re.search(r'inline static void ' + name + r'\(', l))
    body_start = next(i for i in range(start, len(lines)) if lines[i].strip() == '{') + 1
    end = next(i for i in range(body_start, len(lines)) if lines[i] == '        }')
    return lines[body_start:end]


def floatify(line):
    return NUM.sub(lambda m: m.group(1) + 'f', line)


def convert(body, mode):
    out = []
    if mode == 'envall':
        body = body[:next(i for i, l in enumerate(body) if l.strip() == '// robot self-collisions')]
    fk_marked = False
    for l in body:
        s = l.strip()
        m = re.match(r'std::array<FloatVector<rake, 1>, (\d+)> (\w+);', s)
        if m:
            out.append(f'    float {m.group(2)}[{m.group(1)}];')
            continue
        if s.startswith('for (auto i = 0U; i < 59; ++i)'):
            break  # sphere_fk copy-out loop; replaced below
        if mode == 'fkcc' and not fk_marked and s == '// environment vs. robot collisions':
            out.append('    FK_DONE();')
            fk_marked = True
        l = l.replace('sin(x[', 'vamp_sinf(x[').replace('cos(x[', 'vamp_cosf(x[')
        m2 = re.search(r'sphere_environment_in_collision\(environment, y\[(\d+)\]', l)
        if m2:  # pass the sphere index (y index / 4): 0..58 robot spheres, 59.. link bounding spheres
            l = l.replace('sphere_environment_in_collision(environment, ', f'ENV_HIT({int(m2.group(1)) // 4}, ')
        l = l.replace('sphere_sphere_self_collision<decltype(x[0])>(', 'SELF_HIT(')
        if mode == 'envall':
            l = l.replace('ENV_HIT(', 'ENV_ALL(').replace('return false;', ';')
        l = l.replace('return false;', 'return 0;').replace('return true;', 'return 1;')
        out.append(floatify(l[8:] if l.startswith('        ') else l))
    if mode == 'fkcc':
        assert fk_marked, 'FK/CC boundary not found'
    return out


def main():
    src = open(sys.argv[1]).read()
    assert 'static constexpr std::size_t n_spheres = 59;' in src
    fk = convert(extract(src, 'sphere_fk'), 'fk')
    cc = convert(extract(src, 'fkcc'), 'fkcc')
    with open(sys.argv[2], 'w') as f:
        f.write('// GENERATED by tools/gen_panda_fk.py from VAMP robots/panda.hh (Apache-2.0, see VENDORED.md).\n')
        f.write('// Do not edit; regenerate instead.\n')
        f.write('#include "panda.h"\n#include "vmath.h"\n#include "cc.h"\n\n')
        f.write('#define ENV_HIT(id, x, y, z, r) CC_ENV((id), (x), (y), (z), (r))\n')
        f.write('#define SELF_HIT(ax, ay, az, ar, bx, by, bz, br) cc_self_pair((ax), (ay), (az), (ar), (bx), (by), (bz), (br))\n')
        f.write('#define FK_DONE() cc_fk_done()\n\n')
        f.write('void panda_sphere_fk(const float *x, float out[PANDA_N_SPHERES][4])\n{\n')
        f.write('\n'.join(fk))
        f.write('\n    for (int i = 0; i < PANDA_N_SPHERES; ++i)\n        for (int k = 0; k < 4; ++k)\n'
                '            out[i][k] = y[i * 4 + k];\n}\n\n')
        f.write('// 1 = collision-free (VAMP fkcc semantics)\nint panda_fkcc(const float *x)\n{\n')
        f.write('\n'.join(cc))
        f.write('\n}\n')
        ea = convert(extract(src, 'fkcc'), 'envall')
        f.write('\n#ifdef ENV_STATS\n// Host experiment B: every environment query of one pose in hierarchy order, no early exit\n'
                '#define ENV_ALL(id, x, y, z, r) envstat_all_query((id), (x), (y), (z), (r))\n'
                'void panda_env_all(const float *x)\n{\n')
        f.write('\n'.join(ea))
        f.write('\n}\n#endif\n')


if __name__ == '__main__':
    main()
