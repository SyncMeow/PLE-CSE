#!/usr/bin/env python3
"""Generate Platform/accel/rtl/ple/ple_scu.sv (self-collision unit) from the golden pair tables.

Input: output of host/fx_dump_scu (golden pairs and thresholds, fx_pose.c). The result is a boolean
(any inner pair of any colliding outer pair), so the order of the checks is free. Pairs are packed into
"entries": one broadcast sphere a and up to S spheres b (one per lane) with their thresholds.
  outer entries: the 21 link-bounding pairs grouped by a (4 rows here)
  filter entries: for each outer pair g = (link A, link B): the outer sphere of B against the rows a in A (S per entry),
                  thresholds from fx_pose.c (FILT lines): a row that misses has no inner hit
  inner entries: for each row a of g: a against the columns b in B (S per entry)
The generator checks that every outer pair's inner pairs are exactly A x B before relying on that.
Pipeline: entry ROM (e) -> operand mux -> squares -> sum + compare -> hit register; outer hits fill a group mask, the
filter entries of the hit groups fill a row mask, then only the entries of those rows are issued; the first inner hit
ends the check.
Usage: gen_fx_scu_rtl.py <dump.txt> <out.sv> [S]
"""
import sys
from collections import OrderedDict


def lit(v, w):
    return f"{w}'d{v}"


def main():
    dump, out = sys.argv[1], sys.argv[2]
    S = int(sys.argv[3]) if len(sys.argv) > 3 else 8
    outer, inner, filt = [], {}, {}
    for line in open(dump):
        f = line.split()
        if f[0] == 'OUTER':
            outer.append((int(f[1]), int(f[2]), int(f[3]), int(f[4])))
        elif f[0] == 'INNER':
            inner.setdefault(int(f[1]), []).append((int(f[2]), int(f[3]), int(f[4])))
        elif f[0] == 'FILT':
            filt.setdefault(int(f[1]), []).append((int(f[2]), int(f[3])))
    NG = len(outer)
    # ---- inner groups must be full cross products A x B
    groups = []
    for g in range(NG):
        prs = inner[g]
        A = [a for a, _ in filt[g]]                 # rows in the order of the filter thresholds
        B = sorted({b for _, b, _ in prs})
        assert sorted(A) == sorted({a for a, _, _ in prs}) and len(set(A)) == len(A), f'group {g}: FILT rows differ'
        thr = {(a, b): t for a, b, t in prs}
        assert len(prs) == len(A) * len(B) and len(thr) == len(prs), f'group {g} is not a cross product'
        groups.append((A, B, thr))
    # ---- entries: (kind, a, [(b, thr, group)] up to S)
    entries = []
    rows = OrderedDict()
    for g, (_, a, b, t) in enumerate(outer):
        rows.setdefault(a, []).append((b, t, g))
    for a, lst in rows.items():
        for k in range(0, len(lst), S):
            entries.append(('O', a, lst[k:k + S], None))
    NO = len(entries)
    # filter entries: (kind, outer sphere of B, [(row sphere, filter thr, row id)]); row ids are global
    rid, r0 = {}, 0
    for g, (A, B, thr) in enumerate(groups):
        for a in A:
            rid[(g, a)] = r0
            r0 += 1
    NR = r0
    gstart, gcount = [], []
    for g, (A, B, thr) in enumerate(groups):
        gstart.append(len(entries))
        fl = [(a, t, rid[(g, a)]) for a, t in filt[g]]
        for k in range(0, len(fl), S):
            entries.append(('F', outer[g][2], fl[k:k + S], g))
        gcount.append(len(entries) - gstart[-1])
    NF = len(entries) - NO
    rstart, rcount = [], []
    for g, (A, B, thr) in enumerate(groups):
        for a in A:
            rstart.append(len(entries))
            for k in range(0, len(B), S):
                entries.append(('I', a, [(b, thr[(a, b)], g) for b in B[k:k + S]], g))
            rcount.append(len(entries) - rstart[-1])
    NE = len(entries)
    assert NO <= 4, 'the pairs counter gate needs the outer entries to leave S_OUT before stage 4 (use S >= 8)'
    EW = (NE - 1).bit_length()
    GW = max(1, (NG - 1).bit_length())
    RW = max(1, (NR - 1).bit_length())
    XW = max(GW, RW)
    CW = max(1, max(gcount + rcount).bit_length())
    TW = max(t for e in entries for _, t, _ in e[2]).bit_length()
    assert TW <= 40, 'threshold wider than D2W'
    asrc = sorted({e[1] for e in entries})
    bsrc = [sorted({e[2][l][0] for e in entries if l < len(e[2])}) for l in range(S)]
    AW = max(1, (len(asrc) - 1).bit_length())
    BW = max(1, max(len(x) for x in bsrc) - 1).bit_length()
    print(f'SCUGEN outer_pairs={NG} inner_pairs={sum(len(v) for v in inner.values())} rows={NR} S={S} entries={NE} '
          f'(outer {NO}, filter {NF}) a_sources={len(asrc)} b_sources_per_lane={[len(x) for x in bsrc]} thr_bits={TW}')

    o = []
    o.append('// GENERATED by Platform/sw_rrtc/tools/gen_fx_scu_rtl.py from the golden pair tables. Do not edit.')
    o.append('// SCU: self collision of one pose: collide = 1 when some inner sphere pair (d^2 <= thr) of an outer link pair')
    o.append('// that collides is within its threshold and its row passed the row filter.')
    o.append(f'// {S} lanes; {NO} outer entries, then the filter entries of the hit outer pairs (rows of link A against the')
    o.append(f'// outer sphere of link B), then the inner entries of the rows that pass ({NE} entries in all). Result and pair')
    o.append('// count as golden fx_self_ok_filt(); on FK poses the result equals fx_self_ok() (proof at fx_pose_init).')
    o.append('// The first inner hit ends the check. c is latched at start, so the producer may move on.')
    o.append('// start is accepted only while busy = 0 (busy falls one cycle after done).')
    o.append('// Thresholds include the FK error margin FX_DELTA_FK_MM of fx_dump_scu; a run with another delta needs a')
    o.append('// regenerated SCU.')
    o.append('module ple_scu (')
    o.append('    input  logic                     clk,')
    o.append('    input  logic                     rst_n,')
    o.append('    input  logic                     start,')
    o.append('    input  logic [69:0][2:0][17:0]   c,              // [sphere][axis] signed workspace coords')
    o.append('    output logic                     busy,')
    o.append('    output logic                     done,           // one-cycle pulse, collide valid from then on')
    o.append('    output logic                     collide,')
    o.append('    output logic [9:0]               pairs           // pair tests that reached the compare before done (perf)')
    o.append(');')
    o.append('')
    o.append(f'  localparam int S = {S}, NG = {NG}, NR = {NR}, TW = {TW}, GW = {GW}, RW = {RW}, XW = {XW};   // {NE} entries: {NO} outer, {NF} filter')
    o.append('  localparam int D2W = 40;                             // 3 x (19-bit diff)^2')
    o.append('')
    used = sorted(set(asrc) | {b for x in bsrc for b in x})
    o.append(f'  // latched centres: only the {len(used)} spheres the self check names')
    for sp in used:
        o.append(f'  logic [2:0][17:0] cl_{sp};')
    unused = [sp for sp in range(70) if sp not in used]
    if unused:
        o.append('  logic unused_c;')
        o.append('  assign unused_c = ^{' + ', '.join(f'c[{sp}]' for sp in unused) + '};')
    o.append('')
    # ROM functions
    o.append('  // ---- entry ROM')
    o.append(f'  function automatic logic [{AW - 1}:0] rom_a(input logic [{EW - 1}:0] e);')
    o.append('    unique case (e)')
    for i, e in enumerate(entries):
        o.append(f"      {lit(i, EW)}: return {lit(asrc.index(e[1]), AW)};")
    o.append("      default: return '0;")
    o.append('    endcase')
    o.append('  endfunction')
    o.append(f'  function automatic logic [S-1:0] rom_v(input logic [{EW - 1}:0] e);')
    o.append('    unique case (e)')
    for i, e in enumerate(entries):
        o.append(f"      {lit(i, EW)}: return S'({(1 << len(e[2])) - 1});")
    o.append("      default: return '0;")
    o.append('    endcase')
    o.append('  endfunction')
    o.append(f'  function automatic logic [S-1:0][{BW - 1}:0] rom_b(input logic [{EW - 1}:0] e);')
    o.append(f'    logic [S-1:0][{BW - 1}:0] r;')
    o.append("    r = '0;")
    o.append('    unique case (e)')
    for i, e in enumerate(entries):
        parts = ' '.join(f"r[{l}] = {lit(bsrc[l].index(b), BW)};" for l, (b, _, _) in enumerate(e[2]))
        o.append(f"      {lit(i, EW)}: begin {parts} end")
    o.append('      default: ;')
    o.append('    endcase')
    o.append('    return r;')
    o.append('  endfunction')
    o.append(f'  function automatic logic [S-1:0][TW-1:0] rom_t(input logic [{EW - 1}:0] e);')
    o.append('    logic [S-1:0][TW-1:0] r;')
    o.append("    r = '0;")
    o.append('    unique case (e)')
    for i, e in enumerate(entries):
        parts = ' '.join(f"r[{l}] = {lit(t, TW)};" for l, (_, t, _) in enumerate(e[2]))
        o.append(f"      {lit(i, EW)}: begin {parts} end")
    o.append('      default: ;')
    o.append('    endcase')
    o.append('    return r;')
    o.append('  endfunction')
    o.append(f'  function automatic logic [S-1:0][XW-1:0] rom_x(input logic [{EW - 1}:0] e);   // lane -> outer pair (outer entries) or row (filter)')
    o.append(f'    logic [S-1:0][XW-1:0] r;')
    o.append("    r = '0;")
    o.append('    unique case (e)')
    for i, e in enumerate(entries[:NO + NF]):
        parts = ' '.join(f"r[{l}] = {lit(g, XW)};" for l, (_, _, g) in enumerate(e[2]))
        o.append(f"      {lit(i, EW)}: begin {parts} end")
    o.append('      default: ;')
    o.append('    endcase')
    o.append('    return r;')
    o.append('  endfunction')
    o.append(f'  function automatic logic [{EW - 1}:0] g_start(input logic [{GW - 1}:0] g);')
    o.append('    unique case (g)')
    for g in range(NG):
        o.append(f"      {lit(g, GW)}: return {lit(gstart[g], EW)};")
    o.append("      default: return '0;")
    o.append('    endcase')
    o.append('  endfunction')
    o.append(f'  function automatic logic [{CW - 1}:0] g_count(input logic [{GW - 1}:0] g);')
    o.append('    unique case (g)')
    for g in range(NG):
        o.append(f"      {lit(g, GW)}: return {lit(gcount[g], CW)};")
    o.append("      default: return '0;")
    o.append('    endcase')
    o.append('  endfunction')
    o.append(f'  function automatic logic [{EW - 1}:0] r_start(input logic [RW-1:0] r);')
    o.append('    unique case (r)')
    for r in range(NR):
        o.append(f"      {lit(r, RW)}: return {lit(rstart[r], EW)};")
    o.append("      default: return '0;")
    o.append('    endcase')
    o.append('  endfunction')
    o.append(f'  function automatic logic [{CW - 1}:0] r_count(input logic [RW-1:0] r);')
    o.append('    unique case (r)')
    for r in range(NR):
        o.append(f"      {lit(r, RW)}: return {lit(rcount[r], CW)};")
    o.append("      default: return '0;")
    o.append('    endcase')
    o.append('  endfunction')
    o.append('')
    # control
    o.append("  typedef enum logic [2:0] {S_IDLE, S_OUT, S_WAIT, S_FIL, S_WAIT2, S_IN, S_DRAIN} state_e;")
    o.append("  localparam logic [1:0] K_OUT = 2'd0, K_FIL = 2'd1, K_IN = 2'd2;")
    o.append('  state_e state;')
    o.append(f'  logic [{EW - 1}:0] e;                                // entry being issued')
    o.append(f'  logic [{GW - 1}:0] g;                                // current hit outer pair (filter phase)')
    o.append(f'  logic [{CW - 1}:0] k;                                // entry within the outer pair / row')
    o.append('  logic [NG-1:0] hitm;                                 // outer pairs that collide')
    o.append('  logic [NR-1:0] rowm;                                 // rows that passed the filter and are not issued yet')
    o.append('  logic [RW-1:0] row;                                  // current row (inner phase)')
    o.append('  logic [2:0] drain;')
    o.append('  logic issue; logic [1:0] ikind;')
    o.append('  logic in_hit;                                        // an inner pair collides (stage 3)')
    o.append('  logic pipe_busy;')
    o.append('')
    o.append('  // next hit outer pair at or after index from')
    o.append(f'  function automatic logic [{GW}:0] next_hit(input logic [NG-1:0] m, input int from);')
    o.append('    for (int i = 0; i < NG; ++i) if (i >= from && m[i]) return (GW+1)\'(i);')
    o.append(f"    return (GW+1)'(NG);")
    o.append('  endfunction')
    o.append('  // lowest row still in the mask (NR = none)')
    o.append('  function automatic logic [RW:0] next_row(input logic [NR-1:0] m);')
    o.append('    for (int i = 0; i < NR; ++i) if (m[i]) return (RW+1)\'(i);')
    o.append("    return (RW+1)'(NR);")
    o.append('  endfunction')
    o.append('')
    o.append('  always_comb begin')
    o.append('    issue = (state == S_OUT) || (state == S_FIL) || (state == S_IN);')
    o.append('    ikind = (state == S_IN) ? K_IN : (state == S_FIL) ? K_FIL : K_OUT;')
    o.append('  end')
    o.append('')
    # pipeline
    o.append('  // ---- stage 1: ROM codes')
    o.append(f'  logic v1; logic [1:0] kind1; logic [{AW - 1}:0] a1; logic [S-1:0] lv1; logic [S-1:0][{BW - 1}:0] b1;')
    o.append(f'  logic [S-1:0][TW-1:0] t1; logic [S-1:0][XW-1:0] g1;')
    o.append('  // ---- stage 2: operands')
    o.append('  logic v2; logic [1:0] kind2; logic [2:0][17:0] a2; logic [S-1:0] lv2; logic [S-1:0][2:0][17:0] b2;')
    o.append(f'  logic [S-1:0][TW-1:0] t2; logic [S-1:0][XW-1:0] g2;')
    o.append('  // ---- stage 3: squares')
    o.append('  logic v3; logic [1:0] kind3; logic [S-1:0] lv3; logic [S-1:0][2:0][37:0] sq3;')
    o.append(f'  logic [S-1:0][TW-1:0] t3; logic [S-1:0][XW-1:0] g3;')
    o.append('  logic [S-1:0] hit3;')
    o.append('  // ---- stage 4: compare results (registered: keeps the compare off the control path)')
    o.append(f'  logic v4; logic [1:0] kind4; logic [S-1:0] hit4, lv4; logic [S-1:0][XW-1:0] g4;')
    o.append('')
    o.append('  always_ff @(posedge clk) begin')
    o.append('    a1 <= rom_a(e); lv1 <= rom_v(e); b1 <= rom_b(e); t1 <= rom_t(e); g1 <= rom_x(e);')
    o.append('    kind1 <= ikind;')
    o.append('    // operand muxes list only the spheres an entry can name')
    o.append('    unique case (a1)')
    for i, a in enumerate(asrc):
        o.append(f"      {lit(i, AW)}: a2 <= cl_{a};")
    o.append("      default: a2 <= '0;")
    o.append('    endcase')
    for l in range(S):
        o.append(f'    unique case (b1[{l}])')
        for i, b in enumerate(bsrc[l]):
            o.append(f"      {lit(i, BW)}: b2[{l}] <= cl_{b};")
        o.append(f"      default: b2[{l}] <= '0;")
        o.append('    endcase')
    o.append('    lv2 <= lv1; t2 <= t1; g2 <= g1; kind2 <= kind1;')
    o.append('    for (int l = 0; l < S; ++l)')
    o.append('      for (int x = 0; x < 3; ++x) begin')
    o.append('        logic signed [18:0] d;')
    o.append("        d = 19'(signed'(a2[x])) - 19'(signed'(b2[l][x]));")
    o.append('        sq3[l][x] <= 38\'(d * d);')
    o.append('      end')
    o.append('    lv3 <= lv2; t3 <= t2; g3 <= g2; kind3 <= kind2;')
    o.append('    hit4 <= hit3; g4 <= g3; kind4 <= kind3; lv4 <= lv3;')
    o.append('  end')
    o.append('  always_comb')
    o.append('    for (int l = 0; l < S; ++l)')
    o.append("      hit3[l] = lv3[l] && (D2W'(sq3[l][0]) + D2W'(sq3[l][1]) + D2W'(sq3[l][2]) <= D2W'(t3[l]));")
    o.append('  assign in_hit = v4 && kind4 == K_IN && (|hit4);')
    o.append('  assign pipe_busy = v1 || v2 || v3 || v4;')
    o.append('')
    o.append('  always_ff @(posedge clk) begin')
    o.append('    if (!rst_n) begin')
    o.append("      state <= S_IDLE; busy <= 1'b0; done <= 1'b0; collide <= 1'b0; pairs <= '0;")
    o.append("      v1 <= 1'b0; v2 <= 1'b0; v3 <= 1'b0; v4 <= 1'b0;")
    o.append('    end else begin')
    o.append("      done <= 1'b0;")
    o.append('      v1 <= issue; v2 <= v1; v3 <= v2; v4 <= v3;')
    o.append('      if (v4 && kind4 == K_OUT)')
    o.append('        for (int l = 0; l < S; ++l) if (hit4[l]) hitm[g4[l][GW-1:0]] <= 1\'b1;')
    o.append('      if (v4 && kind4 == K_FIL)                        // no row is taken while filter results land (S_WAIT2)')
    o.append('        for (int l = 0; l < S; ++l) if (hit4[l]) rowm[g4[l][RW-1:0]] <= 1\'b1;')
    o.append('      if (done) busy <= 1\'b0;')
    o.append('      // entries of the last pose still in flight land during S_OUT (none of this pose can be at stage 4 yet)')
    o.append('      if (v4 && state != S_IDLE && state != S_OUT) pairs <= pairs + 10\'($countones(lv4));   // golden count on collision-free poses')
    o.append('      unique case (state)')
    o.append('        S_IDLE: if (start && !busy) begin')
    o.append("          busy <= 1'b1; collide <= 1'b0; hitm <= '0; rowm <= '0; e <= '0; pairs <= '0; state <= S_OUT;")
    o.append('          ' + ' '.join(f'cl_{sp} <= c[{sp}];' for sp in used))
    o.append('        end')
    o.append(f"        S_OUT: if (e == {lit(NO - 1, EW)}) begin state <= S_WAIT; drain <= 3'd0; end else e <= e + 1'b1;")
    o.append('        S_WAIT: begin                                    // let the outer results land in hitm')
    o.append("          drain <= drain + 3'd1;")
    o.append("          if (drain == 3'd4) begin")
    o.append(f'            logic [{GW}:0] ng;')
    o.append('            ng = next_hit(hitm, 0);')
    o.append(f"            if (ng == (GW+1)'(NG)) begin state <= S_IDLE; done <= 1'b1; end")
    o.append(f"            else begin g <= ng[{GW - 1}:0]; e <= g_start(ng[{GW - 1}:0]); k <= '0; state <= S_FIL; end")
    o.append('          end')
    o.append('        end')
    o.append('        S_FIL: if (k == g_count(g) - 1) begin            // filter entries of every hit outer pair')
    o.append(f'          logic [{GW}:0] ng;')
    o.append('          ng = next_hit(hitm, int\'(g) + 1);')
    o.append(f"          if (ng == (GW+1)'(NG)) begin state <= S_WAIT2; drain <= 3'd0; end")
    o.append(f"          else begin g <= ng[{GW - 1}:0]; e <= g_start(ng[{GW - 1}:0]); k <= '0; end")
    o.append('        end else begin')
    o.append("          e <= e + 1'b1; k <= k + 1'b1;")
    o.append('        end')
    o.append('        S_WAIT2: begin                                   // let the filter results land in rowm')
    o.append("          drain <= drain + 3'd1;")
    o.append("          if (drain == 3'd4) begin")
    o.append('            logic [RW:0] nr;')
    o.append('            nr = next_row(rowm);')
    o.append("            if (nr == (RW+1)'(NR)) begin state <= S_IDLE; done <= 1'b1; end")
    o.append("            else begin row <= nr[RW-1:0]; rowm[nr[RW-1:0]] <= 1'b0; e <= r_start(nr[RW-1:0]); k <= '0; state <= S_IN; end")
    o.append('          end')
    o.append('        end')
    o.append('        S_IN: if (in_hit) begin')
    o.append("          collide <= 1'b1; done <= 1'b1; state <= S_IDLE;")
    o.append('        end else if (k == r_count(row) - 1) begin')
    o.append('          logic [RW:0] nr;')
    o.append('          nr = next_row(rowm);')
    o.append("          if (nr == (RW+1)'(NR)) begin state <= S_DRAIN; drain <= 3'd0; end")
    o.append("          else begin row <= nr[RW-1:0]; rowm[nr[RW-1:0]] <= 1'b0; e <= r_start(nr[RW-1:0]); k <= '0; end")
    o.append('        end else begin')
    o.append("          e <= e + 1'b1; k <= k + 1'b1;")
    o.append('        end')
    o.append('        S_DRAIN: if (in_hit) begin')
    o.append("          collide <= 1'b1; done <= 1'b1; state <= S_IDLE;")
    o.append('        end else begin')
    o.append("          drain <= drain + 3'd1;")
    o.append("          if (!pipe_busy && drain != 3'd0) begin done <= 1'b1; state <= S_IDLE; end")
    o.append('        end')
    o.append('        default: state <= S_IDLE;')
    o.append('      endcase')
    o.append('    end')
    o.append('  end')
    o.append('')
    o.append('endmodule')
    open(out, 'w').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
