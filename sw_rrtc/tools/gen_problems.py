#!/usr/bin/env python3
"""MotionBenchMaker Panda problems -> gen/problems_panda.c.

Reuses VAMP's own converters (resources/problem_tar_to_pkl_json.py) and its point-cloud pose
convention (vamp.pointcloud.pos_and_quat_to_matrix), so primitives, start/goal and the `valid`
flag are exactly what VAMP's evaluate_mbm.py sees. Needs a Python with vamp, numpy, pyyaml.
Usage: gen_problems.py <vamp checkout> <out.c>
"""
import importlib.util
import re
import sys
import tarfile
from collections import defaultdict
from pathlib import Path

import vamp
from vamp import pointcloud as vpc
from yaml import CLoader as Loader, load

SCENES = ['table_pick', 'table_under_pick', 'box', 'bookshelf_small', 'bookshelf_tall',
          'bookshelf_thin', 'cage']   # paper Sec. V-A numbering 0..6


def f(x):
    t = f'{float(x):.9g}'
    return (t if ('.' in t or 'e' in t or 'n' in t) else t + '.0') + 'f'


def main():
    root = Path(sys.argv[1])
    spec = importlib.util.spec_from_file_location('conv', root / 'resources' / 'problem_tar_to_pkl_json.py')
    conv = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(conv)
    joints = vamp.panda.joint_names()

    scenes, requests = defaultdict(dict), defaultdict(dict)
    with tarfile.open(root / 'resources' / 'panda' / 'problems.tar.bz2', 'r:bz2') as tar:
        for m in tar.getmembers():
            if not m.isfile():
                continue
            _, prob, fn = m.name.split('/')
            prob = prob.replace('_panda', '')
            data = load(tar.extractfile(m).read(), Loader=Loader)
            idx = int(re.findall(r'\d+', fn)[0])
            if 'scene' in fn:
                scenes[prob][idx] = conv.load_moveit_yaml_scene(data)
            else:
                requests[prob][idx] = conv.load_moveit_yaml_request(data, joints)

    prims, probs = [], []
    for si, name in enumerate(SCENES):
        for idx in sorted(scenes[name]):
            p = {**scenes[name][idx], **requests[name][idx], 'problem': name, 'index': idx}
            valid = bool(conv.test_problem(vamp.panda, p))
            off = len(prims)
            for kind, objs in (('cylinder', p['cylinder']), ('box', p['box'])):
                for o in objs:
                    T = vpc.pos_and_quat_to_matrix(o['position'], o['orientation_quat_xyzw'])
                    if kind == 'box':
                        dim = list(o['half_extents'])
                    else:
                        dim = [o['radius'], o['length'], 0.0]
                    prims.append((0 if kind == 'box' else 1, T[:3, 3], T[:3, :3].reshape(-1), dim))
            assert not p['sphere'], 'sphere primitives are not sampled by VAMP either'
            assert len(p['goals']) == 1
            probs.append((si, int(valid), idx, off, len(prims) - off, p['start'], p['goals'][0]))

    with open(sys.argv[2], 'w') as out:
        out.write('// GENERATED by tools/gen_problems.py from VAMP resources/panda/problems.tar.bz2\n'
                  '// (MotionBenchMaker, via VAMP, Apache-2.0; see VENDORED.md). Do not edit.\n'
                  '#include "problems.h"\n\n')
        out.write(f'const int n_scenes = {len(SCENES)};\n')
        out.write('const char *const scene_names[] = {' + ', '.join(f'"{s}"' for s in SCENES) + '};\n\n')
        out.write(f'const int n_problems = {len(probs)};\n')
        out.write('const problem_t problems[] = {\n')
        for si, valid, idx, off, n, s, g in probs:
            out.write(f'    {{{si}, {valid}, {idx}, {off}, {n}, {{{", ".join(map(f, s))}}}, {{{", ".join(map(f, g))}}}}},\n')
        out.write('};\n\nconst prim_t prims[] = {\n')
        for t, pos, rot, dim in prims:
            out.write(f'    {{{t}, {{{", ".join(map(f, pos))}}}, {{{", ".join(map(f, rot))}}}, {{{", ".join(map(f, dim))}}}}},\n')
        out.write('};\n')
    print(f'{len(probs)} problems, {sum(p[1] for p in probs)} valid, {len(prims)} primitives')
    for si, name in enumerate(SCENES):
        sel = [p for p in probs if p[0] == si]
        print(f'  {si} {name:17s} problems={len(sel)} valid={sum(p[1] for p in sel)} '
              f'prims/problem={sorted(set(p[4] for p in sel))}')


if __name__ == '__main__':
    main()
